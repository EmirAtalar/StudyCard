DATA_DIR = os.path.dirname(os.path.abspath(__file__))

def save_and_verify(filename, items):
    seen = set()
    cleaned = []
    for it in items:
        term = it.get("term", "").strip()
        if term and term not in seen:
            seen.add(term)
            cleaned.append(it)
            
    out_path = os.path.join(DATA_DIR, filename)
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(cleaned, f, ensure_ascii=False, indent=2)
    
    count = len(cleaned)
    print(f"[*] {filename}: {count} adet benzersiz kelime kaydedildi.")
    if count < 1000:
        raise ValueError(f"HATA: {filename} sadece {count} kayıt içeriyor, en az 1000 olmalı!")
    return count


